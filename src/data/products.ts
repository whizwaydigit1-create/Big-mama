import { BotanicalProduct, CurrencyCode, CurrencyRate } from '../types';

export const CURRENCY_RATES: Record<CurrencyCode, CurrencyRate> = {
  USD: { code: 'USD', symbol: '$', rateAgainstUSD: 1.0 },
  GBP: { code: 'GBP', symbol: '£', rateAgainstUSD: 0.78 },
  EUR: { code: 'EUR', symbol: '€', rateAgainstUSD: 0.92 },
};

export function formatPrice(priceUSD: number, currency: CurrencyCode): string {
  const rate = CURRENCY_RATES[currency] || CURRENCY_RATES.USD;
  const converted = priceUSD * rate.rateAgainstUSD;
  return `${rate.symbol}${converted.toFixed(2)}`;
}

